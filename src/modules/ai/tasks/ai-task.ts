import { z } from 'zod';

/**
 * Опис однієї AI-задачі: схема відповіді, промти та ліміти.
 *
 * Нова AI-фіча = один файл у `tasks/` + метод-обгортка в `AiService`:
 * вибір моделі, таймаут, ретраї та маппінг помилок лишаються в сервісі.
 */
export interface AiTask<INPUT, OUTPUT> {
  /** Іде в логи і в `schemaName` — деякі провайдери використовують його як підказку. */
  name: string;
  /** Zod-схема відповіді; SDK валідує нею JSON моделі у рантаймі. */
  schema: z.ZodType<OUTPUT>;
  /** Системний промт — роль і правила, однакові для всіх викликів задачі. */
  system: string;
  /** Промт користувача з конкретного входу. */
  buildPrompt: (input: INPUT) => string;
  maxOutputTokens: number;
  /** Модель, відмінна від сконфігурованої за замовчуванням (опційно). */
  model?: string;
}
